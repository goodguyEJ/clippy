import AppKit
import Carbon.HIToolbox

/// UserDefaults keys. Several match the spec's scripting keys
/// (`defaults write io.github.goodguyej.clipstack ignoreEvents -bool true`).
enum K {
    static let historySize = "historySize"
    static let ignoreEvents = "ignoreEvents"
    static let ignoreOnlyNextEvent = "ignoreOnlyNextEvent"
    static let clipboardCheckInterval = "clipboardCheckInterval"
    static let pasteAutomatically = "pasteAutomatically"
    static let pasteWithoutFormatting = "pasteWithoutFormatting"
    static let searchMode = "searchMode"
    static let sortBy = "sortBy"
    static let saveText = "saveText"
    static let saveImages = "saveImages"
    static let saveFiles = "saveFiles"
    static let popupPosition = "popupPosition"
    static let pinPosition = "pinPosition"
    static let imageHeight = "imageHeight"
    static let previewDelay = "previewDelay"
    static let highlightMatch = "highlightMatch"
    static let showSpecialSymbols = "showSpecialSymbols"
    static let showRecentInMenuBar = "showRecentCopyInMenuBar"
    static let hideMenuBarIcon = "hideMenuBarIcon"
    static let menuIcon = "menuIcon"
    static let showSearch = "showSearch"
    static let showTitle = "showTitle"
    static let showAppIcons = "showApplicationIcons"
    static let showFooter = "showFooter"
    static let ignoredApps = "ignoredApps"
    static let allowedApps = "allowedApps"
    static let ignoreAllAppsExceptListed = "ignoreAllAppsExceptListed"
    static let ignoredTypes = "ignoredPasteboardTypes"
    static let ignoreRegexes = "ignoreRegexp"
    static let clearOnQuit = "clearOnQuit"
    static let clearSystemClipboard = "clearSystemClipboard"
    static let forgetAfterDays = "forgetAfterDays"
    static let hotKeyCode = "hotKeyCode"
    static let hotKeyMods = "hotKeyModifiers"
    static let popupWidth = "popupWidth"
    static let popupHeight = "popupHeight"
    static let popupX = "popupX"
    static let popupY = "popupY"
    static let axPromptVersion = "axPromptVersion"
    static let welcomeShown = "welcomeShown"
}

enum SearchMode: String, CaseIterable, Identifiable {
    case exact, fuzzy, regexp, mixed
    var id: String { rawValue }
    var label: String {
        switch self {
        case .exact: "Exact"
        case .fuzzy: "Fuzzy"
        case .regexp: "Regex"
        case .mixed: "Mixed"
        }
    }
}

enum SortBy: String, CaseIterable, Identifiable {
    case lastCopiedAt, firstCopiedAt, numberOfCopies
    var id: String { rawValue }
    var label: String {
        switch self {
        case .lastCopiedAt: "Last copied"
        case .firstCopiedAt: "First copied"
        case .numberOfCopies: "Number of copies"
        }
    }
}

enum PopupPosition: String, CaseIterable, Identifiable {
    case cursor, caret, center, statusItem, lastPosition
    var id: String { rawValue }
    var label: String {
        switch self {
        case .cursor: "At mouse cursor"
        case .caret: "At text cursor"
        case .center: "Center of screen"
        case .statusItem: "Below menu bar icon"
        case .lastPosition: "Where I last left it"
        }
    }
}

enum PinPosition: String, CaseIterable, Identifiable {
    case top, bottom
    var id: String { rawValue }
    var label: String { self == .top ? "Top" : "Bottom" }
}

enum HighlightStyle: String, CaseIterable, Identifiable {
    case bold, italic, underline, color
    var id: String { rawValue }
    var label: String { rawValue.capitalized }
}

enum MenuIcon: String, CaseIterable, Identifiable {
    case list, clipboard, doc, paperclip
    var id: String { rawValue }
    var symbol: String {
        switch self {
        case .list: "list.clipboard"
        case .clipboard: "clipboard"
        case .doc: "doc.on.clipboard"
        case .paperclip: "paperclip"
        }
    }
}

enum Prefs {
    static let d = UserDefaults.standard

    static let defaultIgnoredTypes = [
        "org.nspasteboard.TransientType",
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.AutoGeneratedType",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        "com.agilebits.onepassword",
        "net.antelle.keeweb",
    ]

    /// Password managers whose copies are never recorded, even when they don't mark them as private.
    static let defaultIgnoredApps = [
        "com.apple.keychainaccess",
        "com.apple.Passwords",
        "com.1password.1password",
        "com.agilebits.onepassword7",
        "com.bitwarden.desktop",
        "org.keepassxc.keepassxc",
    ]

    static func registerDefaults() {
        d.register(defaults: [
            K.historySize: 200,
            K.clipboardCheckInterval: 0.5,
            K.pasteAutomatically: true,
            K.pasteWithoutFormatting: false,
            K.searchMode: SearchMode.exact.rawValue,
            K.sortBy: SortBy.lastCopiedAt.rawValue,
            K.saveText: true, K.saveImages: true, K.saveFiles: true,
            K.popupPosition: PopupPosition.cursor.rawValue,
            K.pinPosition: PinPosition.top.rawValue,
            K.imageHeight: 40.0,
            K.previewDelay: 1.5,
            K.highlightMatch: HighlightStyle.bold.rawValue,
            K.showSpecialSymbols: false,
            K.showRecentInMenuBar: false,
            K.hideMenuBarIcon: false,
            K.menuIcon: MenuIcon.list.rawValue,
            K.showSearch: true, K.showTitle: false, K.showAppIcons: true, K.showFooter: true,
            K.ignoredApps: defaultIgnoredApps,
            K.allowedApps: [String](),
            K.ignoreAllAppsExceptListed: false,
            K.ignoredTypes: defaultIgnoredTypes,
            K.ignoreRegexes: [String](),
            K.clearOnQuit: false,
            K.clearSystemClipboard: false,
            K.forgetAfterDays: 0,
            K.hotKeyCode: kVK_ANSI_V,
            K.hotKeyMods: cmdKey | shiftKey,
            K.popupWidth: 440.0, K.popupHeight: 480.0,
        ])
    }

    private static func e<T: RawRepresentable>(_ k: String, _ def: T) -> T where T.RawValue == String {
        T(rawValue: d.string(forKey: k) ?? "") ?? def
    }

    static var historySize: Int { max(1, min(999, d.integer(forKey: K.historySize))) }
    static var ignoreEvents: Bool {
        get { d.bool(forKey: K.ignoreEvents) }
        set { d.set(newValue, forKey: K.ignoreEvents) }
    }
    static var ignoreOnlyNextEvent: Bool {
        get { d.bool(forKey: K.ignoreOnlyNextEvent) }
        set { d.set(newValue, forKey: K.ignoreOnlyNextEvent) }
    }
    static var checkInterval: Double { min(5, max(0.1, d.double(forKey: K.clipboardCheckInterval))) }
    static var pasteAutomatically: Bool { d.bool(forKey: K.pasteAutomatically) }
    static var pasteWithoutFormatting: Bool { d.bool(forKey: K.pasteWithoutFormatting) }
    static var saveText: Bool { d.bool(forKey: K.saveText) }
    static var saveImages: Bool { d.bool(forKey: K.saveImages) }
    static var saveFiles: Bool { d.bool(forKey: K.saveFiles) }
    static var searchMode: SearchMode { e(K.searchMode, .exact) }
    static var sortBy: SortBy { e(K.sortBy, .lastCopiedAt) }
    static var popupPosition: PopupPosition { e(K.popupPosition, .cursor) }
    static var pinPosition: PinPosition { e(K.pinPosition, .top) }
    static var highlight: HighlightStyle { e(K.highlightMatch, .bold) }
    static var menuIcon: MenuIcon { e(K.menuIcon, .list) }
    static var imageHeight: Double { min(200, max(16, d.double(forKey: K.imageHeight))) }
    static var previewDelay: Double { d.double(forKey: K.previewDelay) }
    static var showSpecialSymbols: Bool { d.bool(forKey: K.showSpecialSymbols) }
    static var showRecentInMenuBar: Bool { d.bool(forKey: K.showRecentInMenuBar) }
    static var hideMenuBarIcon: Bool { d.bool(forKey: K.hideMenuBarIcon) }
    static var showSearch: Bool { d.bool(forKey: K.showSearch) }
    static var showTitle: Bool { d.bool(forKey: K.showTitle) }
    static var showAppIcons: Bool { d.bool(forKey: K.showAppIcons) }
    static var showFooter: Bool { d.bool(forKey: K.showFooter) }
    static var ignoredApps: [String] { d.stringArray(forKey: K.ignoredApps) ?? [] }
    static var allowedApps: [String] { d.stringArray(forKey: K.allowedApps) ?? [] }
    static var allowlistMode: Bool { d.bool(forKey: K.ignoreAllAppsExceptListed) }
    static var ignoredTypes: Set<String> { Set(d.stringArray(forKey: K.ignoredTypes) ?? []) }
    static var ignoreRegexes: [NSRegularExpression] {
        (d.stringArray(forKey: K.ignoreRegexes) ?? []).compactMap { try? NSRegularExpression(pattern: $0) }
    }
    static var clearOnQuit: Bool { d.bool(forKey: K.clearOnQuit) }
    static var clearSystemClipboard: Bool { d.bool(forKey: K.clearSystemClipboard) }
    static var forgetAfterDays: Int { max(0, d.integer(forKey: K.forgetAfterDays)) }
    static var hotKeyCode: Int { d.integer(forKey: K.hotKeyCode) }
    static var hotKeyMods: Int { d.integer(forKey: K.hotKeyMods) }
}
